use specta_typescript::Typescript;
use tauri_specta::{Builder, collect_commands};

/// Where the TypeScript bindings are written (debug builds and tests).
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/bindings.ts");

const BINDINGS_HEADER: &str =
    "// Generated by tauri-specta from src-tauri/src/commands. Do not edit by hand.\n";

/// Commands the screens may call: the design's command list. Keep this list,
/// `APP_COMMANDS` in build.rs and `capabilities/default.json` in step.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            projects::list_projects,
            projects::create_project,
            projects::update_project,
            projects::archive_project,
            projects::delete_project,
            todos::list_todos,
            todos::get_todo,
            todos::create_todo,
            todos::update_todo,
            todos::change_status,
            todos::delete_todo,
            todos::set_todo_parent,
            repeats::set_todo_repeat,
            templates::list_todo_templates,
            templates::save_todo_template,
            templates::rename_todo_template,
            templates::delete_todo_template,
            dependencies::add_dependency,
            dependencies::remove_dependency,
            dependencies::list_dependencies,
            work_logs::list_timeline,
            work_logs::save_work_log,
            work_logs::delete_work_log,
            settings::get_settings,
            settings::update_settings,
            dashboard::get_dashboard,
            dashboard::get_startup_reminder,
            dashboard::ack_reminder,
            gantt::get_gantt,
            reports::generate_report,
            reports::save_report,
            reports::get_report,
            reports::export_report_file,
            backup::list_backups,
            backup::restore_backup,
            backup::open_data_folder,
            backup::choose_backup_mirror,
            backup::clear_backup_mirror,
            backup::restore_backup_file,
            notify::test_notification,
            holidays::list_holidays,
            search::search_todos,
            json_data::export_data,
            json_data::import_data,
        ])
        .typ::<error::AppError>()
        // 「初期値に戻す」 on the settings screen sends this template.
        .constant(
            "DEFAULT_REPORT_TEMPLATE",
            crate::domain::report_template::ReportTemplate::default(),
        )
        .constant(
            "DEFAULT_WEEKLY_REPORT_TEMPLATE",
            crate::domain::report_template::WeeklyReportTemplate::default(),
        )
        // The 表示倍率 the settings screen offers (v0.4.0), and the default.
        .constant("ZOOM_LEVELS", crate::domain::settings::ZOOM_LEVELS)
        .constant("DEFAULT_ZOOM", crate::domain::settings::DEFAULT_ZOOM)
        // IDs and counts are i64; they stay far below 2^53 in this app.
        .dangerously_cast_bigints_to_number()
        // One TS type per Rust type (no separate *_Serialize / *_Deserialize).
        .disable_serde_phases()
}

/// Writes the TypeScript bindings to `path`.
pub fn export_bindings(builder: &Builder<tauri::Wry>, path: &str) -> Result<(), String> {
    builder
        .export(Typescript::default().header(BINDINGS_HEADER), path)
        .map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Command names in the generated bindings (`__TAURI_INVOKE<...>("name"`).
    fn commands_in_bindings() -> Vec<String> {
        let ts = std::fs::read_to_string(BINDINGS_PATH).expect("bindings exist");
        let mut names: Vec<String> = ts
            .split("__TAURI_INVOKE<")
            .skip(1)
            .filter_map(|rest| rest.split("(\"").nth(1))
            .filter_map(|rest| rest.split('"').next())
            .map(str::to_owned)
            .collect();
        names.sort();
        names
    }

    /// The capability must allow exactly the registered commands.
    #[test]
    fn capability_allows_exactly_the_registered_commands() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/capabilities/default.json");
        let json: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        let mut allowed: Vec<String> = json["permissions"]
            .as_array()
            .unwrap()
            .iter()
            .filter_map(|p| p.as_str())
            .filter_map(|p| p.strip_prefix("allow-"))
            .map(|p| p.replace('-', "_"))
            .collect();
        allowed.sort();
        assert_eq!(allowed, commands_in_bindings());
        assert_eq!(allowed.len(), 44);
    }

    /// Regenerates `src/lib/bindings.ts` and fails when the committed file was
    /// out of date, so `cargo test` keeps the screens' types in sync.
    #[test]
    fn bindings_are_up_to_date() {
        let before = std::fs::read_to_string(BINDINGS_PATH).unwrap_or_default();
        export_bindings(&specta_builder(), BINDINGS_PATH).expect("export bindings");
        let after = std::fs::read_to_string(BINDINGS_PATH).unwrap();
        assert!(
            before == after,
            "src/lib/bindings.ts was out of date and has been regenerated; review and commit it"
        );
    }
}
